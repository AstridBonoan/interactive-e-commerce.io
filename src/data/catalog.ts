function clothingVariants(
  prefix: string,
  priceCents: number,
  colors: string[],
): Product["variants"] {
  const sizes = ["S", "M", "L", "XL"];
  return colors.flatMap((color) =>
    sizes.map((size) => ({
      id: `${prefix}-${color.toLowerCase()}-${size.toLowerCase()}`,
      label: `${color} / ${size}`,
      options: { Color: color, Size: size },
      priceCents,
      sku: `${prefix}-${color.slice(0, 3)}-${size}`.toUpperCase(),
      inventory: 8 + ((color.length + size.length) % 7),
    })),
  );
}

function bookVariants(prefix: string, priceCents: number): Product["variants"] {
  return [
    {
      id: `${prefix}-softcover`,
      label: "Softcover",
      options: { Binding: "Softcover" },
      priceCents,
      sku: `${prefix}-SOFT`.toUpperCase(),
      inventory: 14,
    },
    {
      id: `${prefix}-clothbound`,
      label: "Clothbound",
      options: { Binding: "Clothbound" },
      priceCents: priceCents + 1200,
      sku: `${prefix}-CLTH`.toUpperCase(),
      inventory: 8,
    },
  ];
}

function photos(slug: string): string[] {
  return [`/products/${slug}.jpg?v=2`];
}

function applianceVariants(
  prefix: string,
  priceCents: number,
  finishes: string[],
): Product["variants"] {
  return finishes.map((finish, index) => ({
    id: `${prefix}-${finish.toLowerCase().replace(/\s+/g, "-")}`,
    label: finish,
    options: { Finish: finish },
    priceCents: priceCents + index * 800,
    sku: `${prefix}-${finish.slice(0, 3)}`.toUpperCase(),
    inventory: 6 + index * 2,
  }));
}

